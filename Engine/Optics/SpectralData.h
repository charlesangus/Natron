#ifndef NATRON_ENGINE_OPTICS_SPECTRALDATA_H
#define NATRON_ENGINE_OPTICS_SPECTRALDATA_H

// The tables in SpectralData.cpp, generated by tools/optics/convert_spectral.py.

namespace Natron {
namespace Optics {
    namespace SpectralData {

        constexpr int kCmfFirstNm = 360;
        constexpr int kCmfCount = 471;

        struct Illuminant {
            const char* name;
            double firstNm;
            double stepNm;
            int count;
            const double* power;
        };

        constexpr int kIlluminantCount = 20;

        // CIE 1931 2 degree standard observer x, y, z at kCmfFirstNm + i nm.
        extern const double kCmf1931[kCmfCount][3];
        extern const Illuminant kIlluminants[kIlluminantCount];

    } // namespace SpectralData
} // namespace Optics
} // namespace Natron

#endif // NATRON_ENGINE_OPTICS_SPECTRALDATA_H
