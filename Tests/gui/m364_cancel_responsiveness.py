    def pick_renderer(label_start):
        state = {}
        sub = yield from open_renderer_submenu(state)
        found = [a for a in entries(sub) if a.text().replace("&", "").startswith(label_start)] if sub is not None else []
        if found:
            since = time.time() * 1000.0
            before = sched()
            start = time.perf_counter()
            found[0].trigger()
            wall = (time.perf_counter() - start) * 1000.0
            after = sched()
            drawn = sum(ms for begin, ms in storm_frames() if begin >= since)
            ran = (after[0] - before[0]) if (before is not None and after is not None) else -1.0
            beat["switch"][beat["phase"]] = (wall, max(0.0, wall - drawn), ran)
        yield from finish_menu(state)
        return bool(found)

    # The heartbeat: gaps between ticks of a 5 ms timer on the main thread, per phase. For the
    # longest gap of each phase it keeps how much of it the main thread ran and how much it waited
    # for a CPU (/proc schedstat), the rest being time it was blocked: so a stall shows whether
    # the GUI thread was busy, starved by the render's threads, or waiting on something.
    # On the phases whose Storm frames are set aside every gap is kept, as (wall-clock start ms,
    # end ms, length ms, schedstat split), and settled against the frames once they are all
    # published: a frame rendered in the background is published when it ends, after the gap in
    # which the GUI thread waited for it on the GPU may have begun.
    beat = {"last": None, "last_wall_ms": None, "sched": None, "phase": "idle", "max": {}, "raw_max": {},
            "split": {}, "gaps": {}, "frames": {}, "view": None, "picked": None, "first_frame": None,
            "upload_ms": 0.0, "paints_in_gap": 0, "phase_wall_ms": 0.0, "switch": {}}
    timer = QTimer()
    timer.setInterval(HEARTBEAT_MS)
    schedstat = "/proc/self/task/%d/schedstat" % threading.get_native_id()

    def sched():
        try:
            with open(schedstat) as f:
                run_ns, wait_ns = f.read().split()[:2]
            return int(run_ns) / 1e6, int(wait_ns) / 1e6
        except (OSError, ValueError):
            return None

    def view_prop(name, default):
        v = beat["view"]
        value = v.property(name) if v is not None else None
        return default if value is None else value

    def storm_frames():
        """The view's latest drawn Storm frames, as (wall-clock start ms, cost ms)."""
        return [(float(f[0]), float(f[1])) for f in view_prop("natronSceneStormFrames", [])]

    def storm_frame_details():
        """Each of those frames as (start ms, cost ms, passes run, fill complete at its start)."""
        return [(float(f[0]), float(f[1]), int(f[2]) if len(f) > 2 else -1, bool(f[3]) if len(f) > 3 else None)
                for f in view_prop("natronSceneStormFrames", [])]

    def tick():
        now = time.perf_counter()
        now_wall_ms = time.time() * 1000.0
        stat = sched()
        beat["frames"].update(storm_frames())
        if beat["last"] is not None:
            gap = (now - beat["last"]) * 1000.0
            split = (stat[0] - beat["sched"][0], stat[1] - beat["sched"][1]) if (stat is not None and beat["sched"] is not None) else None
            beat["raw_max"][beat["phase"]] = max(beat["raw_max"].get(beat["phase"], 0.0), gap)
            if beat["phase"] in STORM_FRAMES_EXCLUDED:
                beat["gaps"].setdefault(beat["phase"], []).append((beat["last_wall_ms"], now_wall_ms, gap, split))
            elif gap > beat["max"].get(beat["phase"], 0.0):
                beat["max"][beat["phase"]] = gap
                if split is not None:
                    beat["split"][beat["phase"]] = split
        beat["last"] = now
        beat["last_wall_ms"] = now_wall_ms
        beat["sched"] = stat
        if beat["picked"] is not None and beat["first_frame"] is None and view_prop("natronSceneRefineFrames", 0) > 0:
            beat["first_frame"] = now - beat["picked"]
        if beat["phase"] == "converge":
            beat["upload_ms"] = max(beat["upload_ms"], float(view_prop("natronSceneUploadMs", 0.0)))

    timer.timeout.connect(tick)

    def phase(name):
        beat["phase"] = name
        beat["phase_wall_ms"] = time.time() * 1000.0
        beat["view"] = view()

    def settle():
        """Sets each kept gap's length without the time Storm frames ran inside it."""
        beat["frames"].update(storm_frames())
        for name, gaps in beat["gaps"].items():
            longest = None
            for begin, end, gap, split in gaps:
                overlaps = [min(end, start + ms) - max(begin, start) for start, ms in beat["frames"].items()]
                overlaps = [ms for ms in overlaps if ms > 0.0]
                beat["paints_in_gap"] = max(beat["paints_in_gap"], len(overlaps))
                left = max(0.0, gap - sum(overlaps))
                if longest is None or left > longest[0]:
                    longest = (left, split)
            if longest is not None:
                beat["max"][name] = longest[0]
                if longest[1] is not None:
                    beat["split"][name] = longest[1]

    def worst(name=None):
        settle()
        gaps = [beat["max"].get(name, 0.0)] if name else list(beat["max"].values())
        return max(gaps) if gaps else 0.0

    def over_limit():
        settle()
        return {name: round(gap, 1) for name, gap in beat["max"].items() if gap >= STALL_LIMIT_MS}

    def steady_storm_frame_ms():
        """The costliest of the Storm frames the render thread draws for STEADY_NUDGES small
        camera tumbles, back and forth, each waited for from the event loop (a paint never draws a
        frame, and a view that has not changed asks for none), with the heartbeat stopped so they
        count against no phase; None if none of them drew."""
        timer.stop()
        navigation = NatronEngine.natron.getSettings().getParam("viewer3DNavigation")
        original = navigation.getValue() if navigation is not None else None
        if navigation is not None:
            navigation.setValue(1)
        v = view()
        costs = []
        try:
            centre = v.rect().center()

            def mouse(kind, pos, button, buttons):
                event = QMouseEvent(kind, QPointF(pos), QPointF(v.mapToGlobal(pos)), button, buttons, Qt.AltModifier)
                QApplication.sendEvent(v, event)

            for i in range(STEADY_NUDGES):
                since = time.time() * 1000.0
                offset = QPoint(STEADY_NUDGE_PX if i % 2 == 0 else -STEADY_NUDGE_PX, 0)
                mouse(QEvent.MouseButtonPress, centre, Qt.LeftButton, Qt.LeftButton)
                mouse(QEvent.MouseMove, centre + offset, Qt.NoButton, Qt.LeftButton)
                mouse(QEvent.MouseButtonRelease, centre + offset, Qt.LeftButton, Qt.NoButton)
                ok = yield ("until", lambda: any(start >= since for start, ms in storm_frames()), POLL_TIMEOUT_S)
                if not ok:
                    break
                costs.append(max(ms for start, ms in storm_frames() if start >= since))
                for start, ms, passes, complete in storm_frame_details():
                    if start >= since:
                        report("NOTE steady frame %d: %.1f ms, %d pass(es), fill complete at start %r"
                               % (i, ms, passes, complete))
        finally:
            if navigation is not None:
                navigation.setValue(original)
            beat["last"] = None
            timer.start()
        return max(costs) if costs else None

    def steps():
        require(settings.connectInput(0, read), "connect the USDRenderSettings to the USDRead")
        require(viewer.connectInput(0, settings), "connect the Viewer to the USDRenderSettings")
        ok = yield ("until", lambda: viewer_up() or view() is not None, STARTUP_TIMEOUT_S)
