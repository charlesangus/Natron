"""Delegate cancel responsiveness (M364 - Delegate Cancel Responsiveness): changing a Cycles setting,
switching renderer and resetting the viewer while Cycles is still on its first sync never stalls the
GUI thread, and the last settings and renderer are what the final frame shows.

Graph: USDRead into USDRenderSettings, and Viewer1 on the USDRenderSettings node. The scene is
generated by default: a layer of NATRON_TEST_MESHES (default 120) meshes, each referencing a grid of
NATRON_TEST_QUADS x NATRON_TEST_QUADS quads (default 100), written to a temp directory. They are not
instanced, so Cycles syncs every one, and its first sync takes seconds. When NATRON_TEST_SCENE
names a file (the Lobby scene, which lives only on the user's host) the USDRead reads that instead
and the script leaves the camera alone.

A heartbeat, a 5 ms Qt timer on the main thread, records the gap between its ticks (wall clock: a
GUI thread blocked on a lock burns no CPU, so a CPU-time budget would hide it). Starting once Storm
has drawn the scene, the longest gap, including the script's own menu work, must stay under 100 ms
in every phase. The screenshot is taken after the heartbeat stops. Steps:
  - picks Cycles in the view's Renderer submenu and, as soon as the view reports Cycles and while
    Cycles has published no frame (the first sync), sets the settings node's cyclesSamples;
  - picks Storm, then Cycles, again before the sync finishes, and sets cyclesSamples to a new value;
  - disconnects the Viewer (a reset) while Cycles is syncing, reconnects it, and re-picks Cycles if
    the view came back on Storm;
  - waits for the render to converge and checks the final frame is Cycles' at the last
    cyclesSamples (natronSceneMaxSamples, natronSceneSamples, natronSceneDrawnSamples), with no
    renderer error.
If Cycles is not available in the Renderer submenu the run is skipped (exit 0). If the first sync
ends before the script can act on it the "during the first sync" checks fail: raise
NATRON_TEST_MESHES for that machine.

View properties read: natronSceneRenderer, natronSceneSynced, natronSceneShown, natronSceneError,
natronSceneRendererError, natronSceneMaxSamples, natronSceneSamples, natronSceneDrawnSamples,
natronSceneRefineConverged, natronSceneRefineFrames, natronSceneUploadMs.

Run through Tests/gui/run-gui-test.sh. Screenshots and results.txt go to $NATRON_GUI_TEST_OUT
(default build/gui-test-out/). Exit status 0 only if every check passed.
"""
import math
import os
import sys
import tempfile
import threading
import time
import traceback

sys.path.insert(0, os.path.join(os.environ.get("NATRON_GUI_TEST_ROOT", os.getcwd()), "Tests", "gui"))

POLL_TIMEOUT_S = 30.0
REFINE_TIMEOUT_S = 180.0
SYNC_TIMEOUT_S = 180.0
SETTLE_MS = 500
STARTUP_TIMEOUT_S = 60.0
STORM_ID = "HdStormRendererPlugin"
CYCLES_ID = "HdCyclesPlugin"
CAMERA = "/World/Cam"
HEARTBEAT_MS = 5
STALL_LIMIT_MS = 100.0
FIRST_SAMPLES = 5
SECOND_SAMPLES = 9
FINAL_SAMPLES = 13
GRID_SIZE = 10.0
GRID_SPACING = 11.0

try:
    from PySide6.QtCore import QEvent, QPointF, Qt, QTimer
    from PySide6.QtGui import QContextMenuEvent, QMouseEvent
    from PySide6.QtTest import QTest
    from PySide6.QtWidgets import QApplication

    from guitest import (check, finish, plugin_problem, report, require, run, section, shot, viewer_up,
                         widgets_of)

    def write_scene(directory, meshes, quads):
        """Writes grid.usda and scene.usda into directory; returns the scene's path."""
        n = quads
        columns = int(math.ceil(math.sqrt(meshes)))
        step = GRID_SIZE / n
        points = []
        for j in range(n + 1):
            for i in range(n + 1):
                points.append("(%.4f, %.4f, %.4f)" % (i * step, 0.4 * ((i * 7 + j * 13) % 9) / 9.0, j * step))
        counts = ",".join(["4"] * (n * n))
        indices = []
        for j in range(n):
            for i in range(n):
                a = j * (n + 1) + i
                indices.append("%d,%d,%d,%d" % (a, a + 1, a + n + 2, a + n + 1))
        with open(os.path.join(directory, "grid.usda"), "w") as f:
            f.write('#usda 1.0\n(\n    defaultPrim = "Grid"\n)\n\n')
            f.write('def Mesh "Grid"\n{\n')
            f.write("    int[] faceVertexCounts = [%s]\n" % counts)
            f.write("    int[] faceVertexIndices = [%s]\n" % ",".join(indices))
            f.write("    point3f[] points = [%s]\n" % ", ".join(points))
            f.write("    uniform token subdivisionScheme = \"none\"\n")
            f.write("    color3f[] primvars:displayColor = [(0.6, 0.6, 0.6)]\n}\n")
        rows = (meshes + columns - 1) // columns
        scene = os.path.join(directory, "scene.usda")
        with open(scene, "w") as f:
            f.write('#usda 1.0\n(\n    defaultPrim = "World"\n    metersPerUnit = 0.01\n    upAxis = "Y"\n)\n\n')
            f.write('def Xform "World"\n{\n')
            for k in range(meshes):
                x = (k % columns) * GRID_SPACING
                z = (k // columns) * GRID_SPACING
                f.write('    def Mesh "Grid%d" (\n        references = @./grid.usda@\n    )\n    {\n' % k)
                f.write('        double3 xformOp:translate = (%.2f, 0, %.2f)\n' % (x, z))
                f.write('        uniform token[] xformOpOrder = ["xformOp:translate"]\n    }\n')
            f.write('    def Camera "Cam"\n    {\n        float focalLength = 18\n')
            f.write('        float horizontalAperture = 20.955\n        float verticalAperture = 20.955\n')
            f.write('        double3 xformOp:translate = (%.1f, %.1f, %.1f)\n'
                    % (columns * GRID_SPACING / 2, 70.0 + rows * 4, rows * GRID_SPACING + 90.0))
            f.write('        float3 xformOp:rotateXYZ = (-22, 0, 0)\n')
            f.write('        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:rotateXYZ"]\n    }\n')
            f.write('    def DistantLight "Sun"\n    {\n        float inputs:intensity = 3\n'
                    '        float3 xformOp:rotateXYZ = (-50, 30, 0)\n'
                    '        uniform token[] xformOpOrder = ["xformOp:rotateXYZ"]\n    }\n}\n')
        return scene

    user_scene = os.environ.get("NATRON_TEST_SCENE", "")
    if user_scene:
        scene_path = user_scene
        require(os.path.isfile(scene_path), "NATRON_TEST_SCENE names a file (%s)" % scene_path)
    else:
        meshes = int(os.environ.get("NATRON_TEST_MESHES", "120"))
        quads = int(os.environ.get("NATRON_TEST_QUADS", "100"))
        scene_path = write_scene(tempfile.mkdtemp(prefix="m364-"), meshes, quads)

    read = app.createNode("USDRead")
    require(read is not None, "create USDRead", plugin_problem("USDRead"))
    require(read.getParam("filename") is not None, "USDRead has a filename parameter")
    read.getParam("filename").setValue(scene_path)
    settings = app.createNode("USDRenderSettings")
    require(settings is not None, "create USDRenderSettings", plugin_problem("USDRenderSettings"))
    viewer = app.getNode("Viewer1")
    if viewer is None:
        viewer = app.createNode("Viewer")
    require(viewer is not None, "a Viewer exists")
    read.setPosition(0, 0)
    settings.setPosition(0, 100)
    viewer.setPosition(200, 200)

    _held = []

    def hold(w):
        if w is not None:
            _held.append(w)
        return w

    _view = [None]
    scan = {"max_ms": 0.0}

    def view():
        # Walking every widget takes the GUI thread tens of ms, which the heartbeat would count
        # against Natron: the view found is kept until it is hidden or deleted.
        v = _view[0]
        try:
            if v is not None and v.isVisible():
                return v
        except RuntimeError:
            pass
        t = time.perf_counter()
        views = [w for w in widgets_of("SceneViewport") if w.isVisible()]
        scan["max_ms"] = max(scan["max_ms"], (time.perf_counter() - t) * 1000.0)
        _view[0] = hold(views[0]) if views else None
        return _view[0]

    def prop(name):
        v = view()
        return v.property(name) if v is not None else None

    def num(name, default=-1):
        value = prop(name)
        return default if value is None else value

    def scene_drawn():
        v = view()
        return (v is not None and bool(v.property("natronSceneSynced")) and bool(v.property("natronSceneShown"))
                and not v.property("natronSceneError"))

    def cycles_first_sync():
        """The view is on Cycles and Cycles has not published a frame: it is still syncing the scene
        (a frame needs a sample, which needs the sync done)."""
        return (prop("natronSceneRenderer") == CYCLES_ID and num("natronSceneRefineFrames", 0) == 0
                and num("natronSceneSamples") <= 0)

    def main_gui():
        guis = [w for w in widgets_of("Gui") if w.isVisible()]
        return hold(guis[0]) if guis else None

    def activate_main_window():
        gui = main_gui()
        if gui is not None:
            gui.activateWindow()
            gui.raise_()
        QApplication.processEvents()

    def popup():
        return QApplication.activePopupWidget()

    def post_context_menu(v, state):
        centre = v.rect().center()

        def post():
            press = QMouseEvent(QEvent.MouseButtonPress, QPointF(centre), QPointF(v.mapToGlobal(centre)),
                                Qt.RightButton, Qt.RightButton, Qt.NoModifier)
            QApplication.sendEvent(v, press)
            event = QContextMenuEvent(QContextMenuEvent.Mouse, centre, v.mapToGlobal(centre), Qt.NoModifier)
            QApplication.sendEvent(v, event)
            state["closed"] = True

        QTimer.singleShot(0, post)

    def close_menus():
        for _ in range(4):
            p = popup()
            if p is None:
                break
            QTest.keyClick(p, Qt.Key_Escape)
            QApplication.processEvents()

    def open_renderer_submenu(state):
        activate_main_window()
        v = view()
        if v is None:
            return None
        post_context_menu(v, state)
        ok = yield ("until", lambda: popup() is not None, POLL_TIMEOUT_S)
        if not ok:
            return None
        menu = hold(popup())
        action = None
        for a in menu.actions():
            if a.text().replace("&", "") == "Renderer" and a.menu() is not None:
                action = a
        if action is None:
            return None
        hold(action)
        sub = hold(action.menu())
        menu.setActiveAction(action)
        QTest.keyClick(menu, Qt.Key_Right)
        yield ("until", lambda: sub.isVisible(), 5.0)
        return sub

    def finish_menu(state):
        close_menus()
        yield ("until", lambda: state.get("closed", False), POLL_TIMEOUT_S)

    def entries(sub):
        return [a for a in sub.actions() if not a.isSeparator()]

    def renderer_labels():
        """Steps that list the Renderer submenu's labels; returns them, or None without a menu."""
        state = {}
        sub = yield from open_renderer_submenu(state)
        labels = [a.text().replace("&", "") for a in entries(sub)] if sub is not None else None
        yield from finish_menu(state)
        return labels

    def pick_renderer(label_start):
        state = {}
        sub = yield from open_renderer_submenu(state)
        found = [a for a in entries(sub) if a.text().replace("&", "").startswith(label_start)] if sub is not None else []
        if found:
            found[0].trigger()
        yield from finish_menu(state)
        return bool(found)

    # The heartbeat: gaps between ticks of a 5 ms timer on the main thread, per phase. For the
    # longest gap of each phase it keeps how much of it the main thread ran and how much it waited
    # for a CPU (/proc schedstat), the rest being time it was blocked: so a stall shows whether
    # the GUI thread was busy, starved by the render's threads, or waiting on something.
    beat = {"last": None, "sched": None, "phase": "idle", "max": {}, "split": {}, "view": None,
            "picked": None, "first_frame": None, "upload_ms": 0.0}
    timer = QTimer()
    timer.setInterval(HEARTBEAT_MS)
    schedstat = "/proc/self/task/%d/schedstat" % threading.get_native_id()

    def sched():
        try:
            with open(schedstat) as f:
                run_ns, wait_ns = f.read().split()[:2]
            return int(run_ns) / 1e6, int(wait_ns) / 1e6
        except (OSError, ValueError):
            return None

    def view_prop(name, default):
        v = beat["view"]
        value = v.property(name) if v is not None else None
        return default if value is None else value

    def tick():
        now = time.perf_counter()
        stat = sched()
        if beat["last"] is not None:
            gap = (now - beat["last"]) * 1000.0
            if gap > beat["max"].get(beat["phase"], 0.0):
                beat["max"][beat["phase"]] = gap
                if stat is not None and beat["sched"] is not None:
                    beat["split"][beat["phase"]] = (stat[0] - beat["sched"][0], stat[1] - beat["sched"][1])
        beat["last"] = now
        beat["sched"] = stat
        if beat["picked"] is not None and beat["first_frame"] is None and view_prop("natronSceneRefineFrames", 0) > 0:
            beat["first_frame"] = now - beat["picked"]
        if beat["phase"] == "converge":
            beat["upload_ms"] = max(beat["upload_ms"], float(view_prop("natronSceneUploadMs", 0.0)))

    timer.timeout.connect(tick)

    def phase(name):
        beat["phase"] = name
        beat["view"] = view()

    def worst(name=None):
        gaps = [beat["max"].get(name, 0.0)] if name else list(beat["max"].values())
        return max(gaps) if gaps else 0.0

    def steps():
        require(settings.connectInput(0, read), "connect the USDRenderSettings to the USDRead")
        require(viewer.connectInput(0, settings), "connect the Viewer to the USDRenderSettings")
        ok = yield ("until", lambda: viewer_up() or view() is not None, STARTUP_TIMEOUT_S)
        require(ok, "the viewer is up")
        ok = yield ("until", scene_drawn, SYNC_TIMEOUT_S)
        require(ok, "the scene view shows the scene on Storm (%r)" % (prop("natronSceneError"),))
        yield ("sleep", SETTLE_MS)
        cam = settings.getParam("camera")
        if not user_scene and cam is not None:
            ok = yield ("until", lambda: CAMERA in [str(o) for o in cam.getOptions()], POLL_TIMEOUT_S)
            if ok:
                cam.set([str(o) for o in cam.getOptions()].index(CAMERA))
                yield ("sleep", SETTLE_MS)
            else:
                report("NOTE %s is not among the settings' cameras %r" % (CAMERA, [str(o) for o in cam.getOptions()]))
        message = read.getPersistentMessage()
        if message:
            report("NOTE USDRead says %r" % (message,))
        samples = settings.getParam("cyclesSamples")

        labels = yield from renderer_labels()
        report("NOTE Renderer submenu: %r" % (labels,))
        if not labels or not any(l.startswith("Cycles") and "unavailable" not in l for l in labels):
            report("SKIP Cycles is not available in this build (%r)" % (labels,))
            return
        require(samples is not None, "the USDRenderSettings has a cyclesSamples parameter")

        section("first sync")
        timer.start()
        phase("start Cycles")
        ok = yield from pick_renderer("Cycles")
        require(ok, "the Renderer submenu has a Cycles entry")
        t0 = time.perf_counter()
        beat["picked"] = t0
        ok = yield ("until", lambda: prop("natronSceneRenderer") == CYCLES_ID, POLL_TIMEOUT_S)
        require(ok, "picking Cycles switches the view (%r)" % (prop("natronSceneRenderer"),))
        in_sync = cycles_first_sync()
        check(in_sync, "Cycles is still on its first sync when the setting changes (raise NATRON_TEST_MESHES if not)")
        phase("change setting")
        samples.set(FIRST_SAMPLES)
        yield ("sleep", 100)
        report("NOTE first sync still running %.2f s after Cycles was picked: %r"
               % (time.perf_counter() - t0, cycles_first_sync()))
        check(worst("start Cycles") < STALL_LIMIT_MS and worst("change setting") < STALL_LIMIT_MS,
              "picking Cycles and changing a setting does not stall the GUI (%.1f, %.1f ms)"
              % (worst("start Cycles"), worst("change setting")))

        section("renderer switches")
        phase("switch to Storm")
        ok = yield from pick_renderer("Storm")
        check(ok, "the Renderer submenu has a Storm entry")
        phase("back to Cycles")
        ok = yield from pick_renderer("Cycles")
        check(ok, "the Renderer submenu has a Cycles entry again")
        ok = yield ("until", lambda: prop("natronSceneRenderer") == CYCLES_ID, POLL_TIMEOUT_S)
        check(ok, "the view is on Cycles again (%r)" % (prop("natronSceneRenderer"),))
        phase("change setting again")
        samples.set(SECOND_SAMPLES)
        yield ("sleep", 100)
        for name in ("switch to Storm", "back to Cycles", "change setting again"):
            check(worst(name) < STALL_LIMIT_MS, "%s does not stall the GUI (%.1f ms)" % (name, worst(name)))

        section("viewer reset")
        phase("reset viewer")
        viewer.disconnectInput(0)
        yield ("sleep", 200)
        phase("reconnect viewer")
        samples.set(FINAL_SAMPLES)
        require(viewer.connectInput(0, settings), "reconnect the Viewer to the USDRenderSettings")
        ok = yield ("until", lambda: view() is not None, STARTUP_TIMEOUT_S)
        require(ok, "the scene view is back")
        if prop("natronSceneRenderer") != CYCLES_ID:
            ok = yield from pick_renderer("Cycles")
            check(ok, "re-picking Cycles after the reset")
            ok = yield ("until", lambda: prop("natronSceneRenderer") == CYCLES_ID, POLL_TIMEOUT_S)
            check(ok, "the view is on Cycles after the reset (%r)" % (prop("natronSceneRenderer"),))
        check(worst("reset viewer") < STALL_LIMIT_MS and worst("reconnect viewer") < STALL_LIMIT_MS,
              "resetting the viewer does not stall the GUI (%.1f, %.1f ms)" % (worst("reset viewer"), worst("reconnect viewer")))

        section("final frame")
        phase("converge")
        ok = yield ("until", lambda: num("natronSceneMaxSamples") == FINAL_SAMPLES and bool(prop("natronSceneRefineConverged"))
                    and num("natronSceneSamples") == FINAL_SAMPLES, REFINE_TIMEOUT_S)
        check(ok, "the render converges at the last cyclesSamples (max %r, samples %r)"
              % (num("natronSceneMaxSamples"), num("natronSceneSamples")))
        ok = yield ("until", lambda: num("natronSceneDrawnSamples") == FINAL_SAMPLES, POLL_TIMEOUT_S)
        check(ok, "the view shows the last settings' frame (drawn %r)" % (num("natronSceneDrawnSamples"),))
        check(prop("natronSceneRenderer") == CYCLES_ID, "the final renderer is Cycles (%r)" % (prop("natronSceneRenderer"),))
        check(not prop("natronSceneRendererError") and not prop("natronSceneError"),
              "no renderer error (%r, %r)" % (prop("natronSceneRendererError"), prop("natronSceneError")))
        # Before the screenshot: grabbing and encoding the whole 1920x1080 screen blocks the GUI
        # thread for over 100 ms under Xvfb by itself.
        timer.stop()
        first = beat["first_frame"]
        report("NOTE Cycles' first frame came %s after it was first picked; longest frame upload while converging %.1f ms"
               % ("never" if first is None else "%.2f s" % first, beat["upload_ms"]))
        report("NOTE longest heartbeat gap per phase (ms): %r" % ({k: round(v, 1) for k, v in beat["max"].items()},))
        report("NOTE of each longest gap, ms the GUI thread ran and waited for a CPU: %r"
               % ({k: (round(r, 1), round(w, 1)) for k, (r, w) in beat["split"].items()},))
        report("NOTE longest walk of the widgets for the view: %.1f ms" % scan["max_ms"])
        check(worst() < STALL_LIMIT_MS, "the GUI thread never stalled over %d ms (worst %.1f ms)" % (STALL_LIMIT_MS, worst()))
        shot("m364-final-frame.png")

    run(steps())
except Exception:
    try:
        check(False, "setup error: " + traceback.format_exc())
        finish()
    except NameError:
        traceback.print_exc()
        os._exit(1)
