"""Delegate cancel responsiveness: changing a Cycles setting,
switching renderer and disconnecting the viewer while Cycles is still on its first sync never stalls
the GUI thread, and the last settings and renderer are what the final frame shows.

Graph: USDRead, its Initial Draw on Full + Load, into USDRenderSettings, and Viewer1 on the
USDRenderSettings node. The scene is generated by default: a layer of NATRON_TEST_MESHES (default 120) meshes, each referencing a grid of
NATRON_TEST_QUADS x NATRON_TEST_QUADS quads (default 100), written to a temp directory. They are not
instanced, so Cycles syncs every one, and its first sync takes seconds. When NATRON_TEST_SCENE
names a file (the Lobby scene, which lives only on the user's host) the USDRead reads that instead
and the script leaves the camera alone.

A heartbeat, a 5 ms Qt timer on the main thread, records the gap between its ticks (wall clock: a
GUI thread blocked on a lock burns no CPU, so a CPU-time budget would hide it). Starting once Storm
has drawn the scene, the longest gap, including the script's own menu work, must stay under 100 ms
in every phase. On the switch to Storm a gap counts without the time Storm frames ran inside it
(natronSceneStormFrames: each frame's start and cost, whether a paint or the render thread drew it
ahead of the paint): on software GL one frame of this scene takes most of a second however little
was edited since, and the GUI thread waits it out, in the paint that draws it or, behind a frame
drawn ahead, when it next composes the window. The frames are checked instead: the first one after
the switch may cost at most a steady Storm frame plus 100 ms, so catch-up work inside it still counts. The steady
frame is the costliest of the frames the render thread draws for a few small camera tumbles after the
switch, each waited for from the event loop, with the heartbeat stopped.
The Renderer entry's trigger, which switches the renderer and lays the view out on the GUI thread,
is timed on its own too and must cost under 100 ms, the Storm frames it draws aside, so a switch's
own cost is told apart from the menu work around it. The screenshot is taken after the heartbeat
stops. Steps:
  - picks Cycles in the view's Renderer submenu and, as soon as the view reports Cycles and while
    Cycles has published no frame (the first sync), sets the settings node's cyclesSamples;
  - picks Storm and waits for its frame, which must come from the Storm engine of the first draw
    (natronSceneEngineCount unchanged, natronSceneEngineHeld): it was kept while Cycles rendered,
    so going back costs a frame, not a sync of the whole scene on the main thread; then picks
    Cycles again and sets cyclesSamples to a new value;
  - disconnects the Viewer's input while Cycles is syncing, which hides the scene view but keeps its
    render (destroying a render mid-pass is ProgressiveRender_Test's), reconnects it, and re-picks
    Cycles if the view came back on Storm;
  - waits for the render to converge and checks the final frame is Cycles' at the last
    cyclesSamples (natronSceneMaxSamples, natronSceneSamples, natronSceneDrawnSamples), with no
    renderer error;
  - with the generated scene only: rewrites the grid every mesh references and presses the
    USDRead's Reload, which has Cycles sync every mesh again, then rewrites the scene's light and
    presses Reload again while it does, waiting for each with app.waitForReloads(0) polled from
    the event loop. Neither reload, nor the render converging after them, may stall the GUI, and
    the converged frame must differ from the one before the reloads.
If Cycles is not available in the Renderer submenu the run is skipped (exit 0). If the first sync
ends before the script can act on it the "during the first sync" checks fail: raise
NATRON_TEST_MESHES for that machine.

View properties read: natronSceneRenderer, natronSceneSynced, natronSceneShown, natronSceneError,
natronSceneRendererError, natronSceneMaxSamples, natronSceneSamples, natronSceneDrawnSamples,
natronSceneRefineConverged, natronSceneRefineFrames, natronSceneUploadMs, natronSceneEngineCount,
natronSceneEngineHeld, natronSceneLastPaintMs, natronSceneStormFrames.

Run through Tests/gui/run-gui-test.sh. Screenshots and results.txt go to $NATRON_GUI_TEST_OUT
(default build/gui-test-out/). Exit status 0 only if every check passed.
"""
