#!/usr/bin/env bash
#
# Bootstrap a git worktree so build.sh/package.sh work in it, from the host.
# Safe to re-run: every step does nothing when its result is already present.
#
# Usage:
#   tools/ci/local/worktree-init.sh [--skip-assets] [<worktree-path>]
#
# <worktree-path> defaults to the current checkout. Steps:
#   1. git submodule sync + update --init --recursive (nested ones included)
#   2. fetch-assets.sh into the worktree's own build/assets/, skipped when the
#      plugin stamp already matches the pins and the bundles are present
#   3. link .natron-deps to the main checkout's copy
#   4. build/appimagetool-wrapper/ copied from the main checkout, or
#      regenerated by make-appimagetool-wrapper.sh
#
# --skip-assets leaves out the asset fetch; fetch-assets.sh compiles plugins inside the
# shared dev container, which a caller may not want to start.
#
# This script never builds Natron.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"

SKIP_ASSETS=0
TARGET=""
for arg in "$@"; do
    case "${arg}" in
        --skip-assets) SKIP_ASSETS=1 ;;
        -*)
            echo "usage: worktree-init.sh [--skip-assets] [<worktree-path>]" >&2
            exit 1
            ;;
        *) TARGET="${arg}" ;;
    esac
done

WORKTREE="$(cd "${TARGET:-.}" >/dev/null 2>&1 && git rev-parse --show-toplevel)" || {
    echo "worktree-init.sh: ERROR: '${TARGET:-.}' is not inside a git checkout." >&2
    exit 1
}

COMMON_DIR="$(git -C "${WORKTREE}" rev-parse --path-format=absolute --git-common-dir)"
MAIN_CHECKOUT="$(dirname "${COMMON_DIR}")"
IS_MAIN=0
if [[ "$(readlink -f "${MAIN_CHECKOUT}")" == "$(readlink -f "${WORKTREE}")" ]]; then
    IS_MAIN=1
fi

DONE=()
PRESENT=()
NOTES=()

# --- 1. submodules -----------------------------------------------------------
echo "== worktree-init: submodules =="
git -C "${WORKTREE}" submodule sync --recursive >/dev/null
needs_update=0
if git -C "${WORKTREE}" submodule status --recursive | grep -q '^[-+U]'; then
    needs_update=1
fi
if [[ "${needs_update}" == "1" ]]; then
    git -C "${WORKTREE}" submodule update --init --recursive
    DONE+=("submodules initialised")
else
    PRESENT+=("submodules (all checked out)")
fi

# --- 2. assets ---------------------------------------------------------------
echo "== worktree-init: assets =="
ASSETS_DIR="${WORKTREE}/build/assets"
FETCH_ASSETS="${WORKTREE}/tools/ci/local/fetch-assets.sh"

# The pins live in fetch-assets.sh as *_REF assignments plus PLUGINS_WANT;
# evaluating just those lines yields the stamp content a finished fetch writes.
assets_current() {
    local wanted
    [[ -f "${ASSETS_DIR}/Plugins/.natron-plugin-pins" && -f "${ASSETS_DIR}/CImg/CImg.h" ]] || return 1
    wanted="$(
        eval "$(grep -E '^[A-Z0-9_]+_(REF|REPO)=|^PLUGINS_WANT=' "${FETCH_ASSETS}")"
        printf '%s' "${PLUGINS_WANT:-}"
    )"
    [[ -n "${wanted}" && "$(cat "${ASSETS_DIR}/Plugins/.natron-plugin-pins")" == "${wanted}" ]] || return 1
    local bundle
    for bundle in Plugins/metadataCompare Plugins/metadataContribute Plugins/metadataTimeCode TestPlugins/metadataPrint; do
        [[ -d "${ASSETS_DIR}/${bundle}.ofx.bundle" ]] || return 1
    done
    return 0
}

if [[ "${SKIP_ASSETS}" == "1" ]]; then
    NOTES+=("assets skipped (--skip-assets)")
elif [[ ! -x "${FETCH_ASSETS}" ]]; then
    echo "worktree-init.sh: ERROR: ${FETCH_ASSETS} not found." >&2
    exit 1
elif assets_current; then
    PRESENT+=("build/assets (plugin pins match)")
else
    "${FETCH_ASSETS}"
    DONE+=("build/assets fetched")
fi

# --- 3. .natron-deps ---------------------------------------------------------
echo "== worktree-init: .natron-deps =="
DEPS_LINK="${WORKTREE}/.natron-deps"
if [[ "${IS_MAIN}" == "1" ]]; then
    NOTES+=(".natron-deps link not needed in the main checkout")
elif [[ -e "${DEPS_LINK}" || -L "${DEPS_LINK}" ]]; then
    PRESENT+=(".natron-deps")
elif [[ -d "${MAIN_CHECKOUT}/.natron-deps" ]]; then
    ln -s "${MAIN_CHECKOUT}/.natron-deps" "${DEPS_LINK}"
    DONE+=(".natron-deps linked to ${MAIN_CHECKOUT}/.natron-deps")
else
    NOTES+=(".natron-deps not linked: ${MAIN_CHECKOUT}/.natron-deps does not exist")
fi

# --- 4. appimagetool wrapper -------------------------------------------------
echo "== worktree-init: appimagetool wrapper =="
WRAPPER_DIR="${WORKTREE}/build/appimagetool-wrapper"
MAIN_WRAPPER_DIR="${MAIN_CHECKOUT}/build/appimagetool-wrapper"
if [[ -x "${WRAPPER_DIR}/appimagetool" && -f "${WRAPPER_DIR}/appimagetool.real" ]]; then
    PRESENT+=("build/appimagetool-wrapper")
elif [[ "${IS_MAIN}" != "1" && -x "${MAIN_WRAPPER_DIR}/appimagetool" && -f "${MAIN_WRAPPER_DIR}/appimagetool.real" ]]; then
    mkdir -p "${WRAPPER_DIR}"
    cp -p "${MAIN_WRAPPER_DIR}/appimagetool" "${MAIN_WRAPPER_DIR}/appimagetool.real" "${WRAPPER_DIR}/"
    DONE+=("build/appimagetool-wrapper copied from the main checkout")
elif "${SCRIPT_DIR}/make-appimagetool-wrapper.sh" "${WRAPPER_DIR}" 2>/dev/null; then
    DONE+=("build/appimagetool-wrapper generated")
else
    NOTES+=("no appimagetool available; package.sh will download one")
fi

# --- summary -----------------------------------------------------------------
echo
echo "== worktree-init: summary for ${WORKTREE} =="
for item in "${DONE[@]+"${DONE[@]}"}"; do echo "  done:    ${item}"; done
for item in "${PRESENT[@]+"${PRESENT[@]}"}"; do echo "  present: ${item}"; done
for item in "${NOTES[@]+"${NOTES[@]}"}"; do echo "  note:    ${item}"; done
echo
echo "Before building here, run:"
echo "  export NATRON_SKIP_SUBMODULE_UPDATE=1"
echo "so build.sh keeps a pinned libs/OpenFX branch instead of resetting it."
