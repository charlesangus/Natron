#!/usr/bin/env python3
"""Generate Engine/Optics/SpectralData.cpp from realflare's colour tables.

usage: convert_spectral.py <realflare checkout> [--output <SpectralData.cpp>]

The checkout must be at PINNED_COMMIT of https://github.com/beatreichenbach/realflare
(GPL-3.0-or-later). Its flare/api/color/data/*.py hold the CIE tables as Python
literals; they are read with ast.literal_eval, never executed. Written: the CIE
2015 2 degree colour matching functions from 390 to 730 nm at 1 nm, and the
spectral power distributions of ILLUMINANTS at their own sampling. A rerun on the
same checkout is byte-identical.
"""
