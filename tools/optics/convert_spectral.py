import ast
import os
import subprocess
import sys

PINNED_COMMIT = "9ce30b0f5469268969e03e46bc532f22bb1ba98f"
SOURCE_URL = "https://github.com/beatreichenbach/realflare"
OBSERVER = "CIE 2015 2 Degree Standard Observer"
CMF_RANGE = (390, 730)
ILLUMINANTS = ["A", "B", "C", "D50", "D55", "D60", "D65", "D75", "E"] + ["FL%d" % i for i in range(1, 12)]

