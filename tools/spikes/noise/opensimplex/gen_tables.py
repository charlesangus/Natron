#!/usr/bin/env python3
"""Extract the OpenSimplex2S 4D tables from upstream's csharp/OpenSimplex2S.cs.

    gen_tables.py <OpenSimplex2S.cs> <out dir>

Writes os2s4d_grad.inc, os2s4d_lookup_a.inc and os2s4d_lookup_b.inc: bare initializer lists that
both os2s4d.h and os2s4d.slang #include, so the CPU and GPU read bit-identical tables.

The gradients are divided by NORMALIZER_4D here, in double precision and rounded to float as
upstream's static constructor does, so no device-side arithmetic can perturb them.
"""

import re
import struct
import sys

NORMALIZER_4D = 0.11127401889945551


def f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def literal(v):
    s = "%.9g" % v
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def block(src, start_pattern):
    start = re.search(start_pattern, src)
    if not start:
        sys.exit("pattern not found: " + start_pattern)
    depth = 0
    for i in range(start.end() - 1, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start.end() : i]
    sys.exit("unterminated block: " + start_pattern)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = open(sys.argv[1], encoding="utf-8").read()
    out = sys.argv[2]

    grad_src = re.sub(r"//[^\n]*", "", block(src, r"float\[\]\s+grad4\s*=\s*\{"))
    grads = [float(t.rstrip("f")) for t in re.findall(r"-?[0-9.]+f", grad_src)]
    if len(grads) != 160 * 4:
        sys.exit("expected 640 gradient components, found %d" % len(grads))
    grads = [f32(f32(g) / NORMALIZER_4D) for g in grads]

    codes_src = block(src, r"int\[\]\[\]\s+lookup4DVertexCodes\s*=\s*\{")
    rows = [[int(c, 16) for c in re.findall(r"0x[0-9A-Fa-f]+", r)] for r in re.findall(r"new int\[\]\s*\{([^}]*)\}", codes_src)]
    if len(rows) != 256:
        sys.exit("expected 256 lookup rows, found %d" % len(rows))

    lookup_a = []
    lookup_b = []
    for r in rows:
        lookup_a.append(len(lookup_b) | ((len(lookup_b) + len(r)) << 16))
        lookup_b.extend(r)

    header = "// Generated by gen_tables.py from OpenSimplex2 csharp/OpenSimplex2S.cs (CC0). Do not edit.\n"
    with open(out + "/os2s4d_grad.inc", "w") as f:
        f.write(header)
        for i in range(0, len(grads), 4):
            f.write("    " + ", ".join(literal(g) for g in grads[i : i + 4]) + ",\n")
    with open(out + "/os2s4d_lookup_a.inc", "w") as f:
        f.write(header)
        for i in range(0, len(lookup_a), 8):
            f.write("    " + ", ".join("0x%08Xu" % v for v in lookup_a[i : i + 8]) + ",\n")
    with open(out + "/os2s4d_lookup_b.inc", "w") as f:
        f.write(header)
        for i in range(0, len(lookup_b), 16):
            f.write("    " + ", ".join("0x%02Xu" % v for v in lookup_b[i : i + 16]) + ",\n")


if __name__ == "__main__":
    main()
